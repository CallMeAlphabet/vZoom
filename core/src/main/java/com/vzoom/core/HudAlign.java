package com.vzoom.core;

/**
 * Screen anchor for the (optional) zoom HUD. The HUD only renders while the
 * zoom key is held and only when the user has enabled it in the config screen.
 */
public enum HudAlign {
    TOP_LEFT,
    TOP_CENTER,
    TOP_RIGHT,
    BOTTOM_LEFT,
    BOTTOM_CENTER,
    BOTTOM_RIGHT,
    CENTER
}
